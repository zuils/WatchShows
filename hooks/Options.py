####################################################################
# NOTE: At the time that options are created, Manual has no concept of the multiworld or its own world.
#       Options are defined before the world is even created.
#
# Example of creating your own option:
#
#   class MakeThePlayerOP(Toggle):
#       """Should the player be overpowered? Probably not, but you can choose for this to do... something!"""
#       display_name = "Make me OP"
#
#   options["make_op"] = MakeThePlayerOP
#
#
# Then, to see if the option is set, you can call is_option_enabled or get_option_value.
#####################################################################


# To add an option, use the before_options_defined hook below and something like this:
#   options["total_characters_to_win_with"] = TotalCharactersToWinWith
#
class TotalEpisodes(Range):
    """How many episodes (or other subdivisions) do you want to make into checks?"""
    display_name = "Number of episodes"
    range_start = 1
    range_end = 999
    default = 13

class TwoChecksPerEpisode(Toggle):
    """If enabled, each episode gives two checks when completed instead of one."""
    display_name = "Two Checks Per Episode"

class EnableBookmark(Toggle):
    """If enabled, each episode will have a fake check that will help you count how many episodes you've watched."""
    display_name = "Enable Bookmark"

# This is called before any manual options are defined, in case you want to define your own with a clean slate or let Manual define over them
def before_options_defined(options: dict) -> dict:
    options["total_episodes"] = TotalEpisodes
    options["two_checks_per_episode"] = TwoChecksPerEpisode
    options["enable_bookmark"] = EnableBookmark
    return options

# This is called after any manual options are defined, in case you want to see what options are defined or want to modify the defined options
def after_options_defined(options: dict) -> dict:
    return options

# Use this Hook if you want to add your Option to an Option group (existing or not)
def before_option_groups_created(groups: dict[str, list[Type[Option[Any]]]]) -> dict[str, list[Type[Option[Any]]]]:
    # Uses the format groups['GroupName'] = [TotalCharactersToWinWith]
    return groups

def after_option_groups_created(groups: list[OptionGroup]) -> list[OptionGroup]:
    return groups
